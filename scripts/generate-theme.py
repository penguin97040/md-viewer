"""Generate the bundled CSS and native background from design/tokens.json."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
tokens = json.loads((root / 'design/tokens.json').read_text())
colours = {k: v['$value'] for k, v in tokens['color'].items() if '$value' in v}
css = '/* Generated by scripts/generate-theme.py; edit design/tokens.json. */\n:root {\n'
for name, value in colours.items():
    css += f'  --brand-{name}: {value};\n'
css += '}\n'
(root / 'frontend/theme.css').write_text(css)
value = colours['black'].lstrip('#')
go = '// Code generated by scripts/generate-theme.py; DO NOT EDIT.\n\npackage main\n\n'
go += f'var darkBackground = [3]uint8{{0x{value[:2]}, 0x{value[2:4]}, 0x{value[4:6]}}}\n'
(root / 'theme_colours.go').write_text(go)
