"""Generate the bundled CSS and native background from design/tokens.json."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
tokens = json.loads((root / 'design/tokens.json').read_text())
colours = {k: v['$value'] for k, v in tokens['color'].items() if '$value' in v}
css = '/* Generated by scripts/generate-theme.py; edit design/tokens.json. */\n:root {\n'
for name, value in colours.items():
    css += f'  --brand-{name}: {value};\n'
css += '}\n'
(root / 'frontend/theme.css').write_text(css)
value = colours['black'].lstrip('#')
go = '// Code generated by scripts/generate-theme.py; DO NOT EDIT.\n\npackage main\n\n'
go += f'var darkBackground = [3]uint8{{0x{value[:2]}, 0x{value[2:4]}, 0x{value[4:6]}}}\n'
(root / 'theme_colours.go').write_text(go)

# Rust tokens for the GPUI spike (spike-gpui/crates/theme/src/generated.rs).
rust_dir = root / 'spike-gpui/crates/theme/src'
if rust_dir.is_dir():
    rs = '// Generated by scripts/generate-theme.py from design/tokens.json; DO NOT EDIT.\n\n'
    rs += '/// Brand colours as 0xRRGGBB.\n'
    for name, value in colours.items():
        rs += f'pub const BRAND_{name.upper()}: u32 = 0x{value.lstrip("#")};\n'
    for name, value in tokens['color']['illustration'].items():
        if '$value' in value:
            rs += f'pub const ILLUSTRATION_{name.upper()}: u32 = 0x{value["$value"].lstrip("#")};\n'
    rs += '\n/// Sizes in px at 1x.\n'
    for name, value in tokens['size'].items():
        if '$value' in value:
            rs += f'pub const SIZE_{name.upper()}: f32 = {float(value["$value"]["value"])!r};\n'
    for name, value in tokens['space'].items():
        if '$value' in value:
            rs += f'pub const SPACE_{name}: f32 = {float(value["$value"]["value"])!r};\n'
    rs += '\n/// Font families and weights.\n'
    for name, value in tokens['font']['family'].items():
        if '$value' in value:
            rs += f'pub const FONT_{name.upper()}: &str = "{value["$value"][0]}";\n'
    for name, value in tokens['font']['weight'].items():
        if '$value' in value:
            rs += f'pub const WEIGHT_{name.upper()}: f32 = {float(value["$value"])!r};\n'
    (rust_dir / 'generated.rs').write_text(rs)
