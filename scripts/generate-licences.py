#!/usr/bin/env python3
"""Writes the Rust crate list in THIRD-PARTY.md from Cargo.lock and the crates' own metadata.

Lists every crate that is compiled into the executable on Windows, macOS or Linux (normal
dependencies only; build scripts, tests and tools are left out), with its version and licence
expression as the crate declares it.

    python3 scripts/generate-licences.py            # rewrite the list between the markers
    python3 scripts/generate-licences.py --check    # fail if THIRD-PARTY.md is out of date

Needs cargo and the three targets' metadata, which cargo can read without installing them.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "THIRD-PARTY.md"
BEGIN = "<!-- crates:begin (generated by scripts/generate-licences.py) -->"
END = "<!-- crates:end -->"
TARGETS = ["x86_64-pc-windows-msvc", "aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-unknown-linux-gnu"]
WORKSPACE_ONLY = {"md-viewer"}


def shipped(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    meta = json.loads(out)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"] or next(i for i, p in packages.items() if p["name"] == "md-viewer")
    seen, stack = set(), [root]
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        for dep in nodes[cur]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return {(packages[i]["name"], packages[i]["version"]): packages[i] for i in seen}


def table():
    crates = {}
    for target in TARGETS:
        crates.update(shipped(target))
    rows = []
    for (name, version), pkg in sorted(crates.items()):
        if pkg["source"] is None and name.startswith("mdv-") or name in WORKSPACE_ONLY:
            continue
        licence = pkg["license"] or ("see " + (pkg["license_file"] or "the crate source"))
        rows.append(f"| {name} | {version} | {licence.replace('|', '/')} |")
    return "\n".join(["| Crate | Version | Licence |", "|---|---|---|", *rows])


def main():
    text = DOC.read_text()
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{BEGIN}\n{table()}\n{END}{tail}"
    if "--check" in sys.argv:
        if new != text:
            sys.exit("THIRD-PARTY.md is out of date: run python3 scripts/generate-licences.py")
        print("THIRD-PARTY.md is up to date")
    else:
        DOC.write_text(new)
        print(f"wrote {DOC.name}")


main()
